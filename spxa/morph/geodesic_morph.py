"""
Information-geometric and Fisher-Rao geodesic model morphing.

Interpolates stochastic processes along Riemannian geodesics on statistical
manifolds equipped with the Fisher-Rao metric tensor g_ij(θ) and Amari dual
connections (e-geodesics and m-geodesics):

    D²θ / Dα² = 0,   θ(0) = θ_0,  θ(1) = θ_1

References:
  Amari, S.-I. (2016), Information Geometry and Its Applications;
  Rao, C. R. (1945), Information and accuracy attainable in the estimation of statistical parameters;
  Costa, S. I. R. et al. (2015), The Riemannian geometry of Gaussian distributions.
"""

from __future__ import annotations

import math
from typing import Any, Optional, Tuple, Union

import numpy as np

from spxa.core.exactness import ExactnessLevel
from spxa.core.process import Process
from spxa.core.properties import ProcessProperties
from spxa.core.triplet import LevyTriplet
from spxa.morph.base import AbstractMorphEngine
from spxa.story.narrator import CompositionNode, NodeKind


class GeodesicMorphEngine(AbstractMorphEngine):
    r"""
    Morphing engine along Riemannian geodesics in statistical manifolds.
    """

    def morph(
        self,
        p0: Any,
        p1: Any,
        alpha: float,
        connection: str = "riemannian",
        **kwargs: Any,
    ) -> GeodesicMorphedProcess:
        return GeodesicMorphedProcess(
            p0=p0,
            p1=p1,
            alpha=alpha,
            connection=connection,
            **kwargs,
        )


def gaussian_rao_distance(mu0: float, sigma0: float, mu1: float, sigma1: float) -> float:
    r"""
    Exact Fisher-Rao geodesic distance between two univariate Gaussian models
    :math:`\mathcal{N}(\mu_0, \sigma_0^2)` and :math:`\mathcal{N}(\mu_1, \sigma_1^2)`:

    .. math::
        d_R(\theta_0, \theta_1) = \sqrt{2} \ln\left( \frac{1 + \delta}{1 - \delta} \right), \quad
        \delta = \sqrt{ \frac{(\mu_1 - \mu_0)^2 + 2(\sigma_1 - \sigma_0)^2}{(\mu_1 - \mu_0)^2 + 2(\sigma_1 + \sigma_0)^2} }
    """
    d_mu = mu1 - mu0
    d_sig = sigma1 - sigma0
    s_sig = sigma1 + sigma0

    num = d_mu**2 + 2.0 * (d_sig**2)
    den = d_mu**2 + 2.0 * (s_sig**2)
    if den <= 0.0:
        return 0.0

    delta = math.sqrt(max(0.0, min(1.0 - 1e-15, num / den)))
    if delta >= 1.0:
        return float(np.inf)
    return math.sqrt(2.0) * math.log((1.0 + delta) / (1.0 - delta))


def gaussian_geodesic_path(
    mu0: float, sigma0: float, mu1: float, sigma1: float, alpha: float
) -> Tuple[float, float]:
    r"""
    Evaluate exact Fisher-Rao Riemannian geodesic coordinates :math:`(\mu(\alpha), \sigma(\alpha))`
    on the hyperbolic statistical manifold :math:`\mathbb{H}^2` at parameter :math:`\alpha \in [0, 1]`.
    """
    if alpha <= 0.0:
        return mu0, sigma0
    if alpha >= 1.0:
        return mu1, sigma1

    # Vertical geodesic case: mu0 == mu1
    if abs(mu1 - mu0) < 1e-10:
        # sigma(alpha) = sigma0 * (sigma1 / sigma0)^alpha
        sig_alpha = sigma0 * ((sigma1 / sigma0) ** alpha)
        return mu0, sig_alpha

    # Transformation to hyperbolic coordinates x = mu / sqrt(2), y = sigma
    x0, y0 = mu0 / math.sqrt(2.0), sigma0
    x1, y1 = mu1 / math.sqrt(2.0), sigma1

    # In upper half plane, geodesics are semicircles orthogonal to y=0:
    # (x - c)^2 + y^2 = R^2
    # Solving for center c:
    # (x0 - c)^2 + y0^2 = (x1 - c)^2 + y1^2 => c = ((x1^2 + y1^2) - (x0^2 + y0^2)) / (2(x1 - x0))
    c = ((x1**2 + y1**2) - (x0**2 + y0**2)) / (2.0 * (x1 - x0))
    r_sq = (x0 - c) ** 2 + y0**2
    r = math.sqrt(max(1e-12, r_sq))

    # Angle parametrization: x - c = R cos(phi), y = R sin(phi)
    phi0 = math.atan2(y0, x0 - c)
    phi1 = math.atan2(y1, x1 - c)

    # In hyperbolic metric, hyperbolic distance s along circle is given by:
    # tanh(s/2) or lambda = ln(tan(phi / 2))
    u0 = math.log(max(1e-15, math.tan(phi0 / 2.0)))
    u1 = math.log(max(1e-15, math.tan(phi1 / 2.0)))

    # Geodesic is linear in hyperbolic arc coordinate u:
    u_alpha = (1.0 - alpha) * u0 + alpha * u1
    phi_alpha = 2.0 * math.atan(math.exp(u_alpha))

    x_alpha = c + r * math.cos(phi_alpha)
    y_alpha = r * math.sin(phi_alpha)

    mu_alpha = x_alpha * math.sqrt(2.0)
    sigma_alpha = max(1e-8, y_alpha)

    return mu_alpha, sigma_alpha


class GeodesicMorphedProcess(Process):
    r"""
    Stochastic process generated by following the information-geometric geodesic.

    Parameters
    ----------
    p0 :
        Base process at :math:`\alpha = 0`.
    p1 :
        Target process at :math:`\alpha = 1`.
    alpha :
        Homotopy / geodesic parameter in :math:`[0, 1]`.
    connection :
        Geometric connection:
        - ``"riemannian"``: Levi-Civita geodesic (Fisher-Rao metric).
        - ``"exponential"``: Amari e-geodesic (:math:`\nabla^{(1)}`, natural coordinates).
        - ``"mixture"``: Amari m-geodesic (:math:`\nabla^{(-1)}`, expectation coordinates).
    """

    def __init__(
        self,
        p0: Process,
        p1: Process,
        alpha: float = 0.5,
        connection: str = "riemannian",
    ) -> None:
        if not (0.0 <= alpha <= 1.0):
            raise ValueError(f"alpha must be in [0, 1], got {alpha}")

        self.p0 = p0
        self.p1 = p1
        self.alpha = float(alpha)
        self.connection = connection.lower()

        # Compute geodesic coordinates
        self.mu_alpha, self.sigma_alpha = self._evaluate_geodesic_params()

        _node = CompositionNode(
            kind=NodeKind.MORPH,
            name=f"GeodesicMorph({p0!r} → {p1!r}; α={alpha:.3f}, {connection})",
            children=[p0._node, p1._node],
            math_note=f"Fisher-Rao geodesic: μ={self.mu_alpha:.4f}, σ={self.sigma_alpha:.4f}",
            reference="Amari (2016); Rao (1945)",
        )

        super().__init__(exactness=ExactnessLevel.EXACT, _node=_node)

    def _evaluate_geodesic_params(self) -> Tuple[float, float]:
        """Extract or compute geodesic parameters."""
        mu0 = float(getattr(self.p0, "mu", 0.0))
        sigma0 = float(getattr(self.p0, "sigma", 1.0))
        mu1 = float(getattr(self.p1, "mu", 0.0))
        sigma1 = float(getattr(self.p1, "sigma", 1.0))

        if self.connection == "exponential":
            # e-geodesic: linear in natural coordinates (theta1 = mu/sigma^2, theta2 = -1/(2 sigma^2))
            th1_0, th2_0 = mu0 / (sigma0**2), -0.5 / (sigma0**2)
            th1_1, th2_1 = mu1 / (sigma1**2), -0.5 / (sigma1**2)
            th1_a = (1.0 - self.alpha) * th1_0 + self.alpha * th1_1
            th2_a = (1.0 - self.alpha) * th2_0 + self.alpha * th2_1
            sig_a = math.sqrt(-0.5 / th2_a)
            mu_a = th1_a * (sig_a**2)
            return mu_a, sig_a

        elif self.connection == "mixture":
            # m-geodesic: linear in expectation coordinates (eta1 = mu, eta2 = mu^2 + sigma^2)
            eta1_0, eta2_0 = mu0, mu0**2 + sigma0**2
            eta1_1, eta2_1 = mu1, mu1**2 + sigma1**2
            eta1_a = (1.0 - self.alpha) * eta1_0 + self.alpha * eta1_1
            eta2_a = (1.0 - self.alpha) * eta2_0 + self.alpha * eta2_1
            mu_a = eta1_a
            sig_a = math.sqrt(max(1e-8, eta2_a - mu_a**2))
            return mu_a, sig_a

        # Default Riemannian Levi-Civita geodesic
        return gaussian_geodesic_path(mu0, sigma0, mu1, sigma1, self.alpha)

    @property
    def rao_distance(self) -> float:
        """Fisher-Rao distance between base and target models."""
        mu0 = float(getattr(self.p0, "mu", 0.0))
        sigma0 = float(getattr(self.p0, "sigma", 1.0))
        mu1 = float(getattr(self.p1, "mu", 0.0))
        sigma1 = float(getattr(self.p1, "sigma", 1.0))
        return gaussian_rao_distance(mu0, sigma0, mu1, sigma1)

    def _triplet(self) -> LevyTriplet:
        from spxa.core.levy_measure import LevyMeasure

        class ZeroLevyMeasure(LevyMeasure):
            def density(self, x: Any) -> np.ndarray:
                return np.zeros_like(np.asarray(x, dtype=float))

            def total_mass(self) -> float:
                return 0.0

            def tail(self, x: float) -> float:
                return 0.0

            def moment(self, n: int) -> float:
                return 0.0

        return LevyTriplet(
            b=self.mu_alpha,
            sigma_sq=self.sigma_alpha**2,
            nu=ZeroLevyMeasure(),
        )

    def _properties(self) -> ProcessProperties:
        return ProcessProperties.combine_morph(self.p0.properties, self.p1.properties, self.alpha)

    def cumulants(self, order: int) -> dict[int, float]:
        res = {1: self.mu_alpha}
        if order >= 2:
            res[2] = self.sigma_alpha**2
        for k in range(3, order + 1):
            res[k] = 0.0
        return res

    def char_func(self, u: Union[float, np.ndarray], t: float = 1.0) -> np.ndarray:
        u_arr = np.asarray(u, dtype=np.complex128)
        return np.exp(1j * u_arr * self.mu_alpha * t - 0.5 * (self.sigma_alpha**2) * (u_arr**2) * t)

    def simulate(
        self,
        n_steps: int,
        n_paths: int = 1,
        T: float = 1.0,
        rng: Optional[np.random.Generator] = None,
    ) -> np.ndarray:
        if rng is None:
            rng = np.random.default_rng()

        dt = float(T) / n_steps
        sqrt_dt = math.sqrt(dt)

        increments = self.mu_alpha * dt + self.sigma_alpha * sqrt_dt * rng.standard_normal(
            (n_paths, n_steps)
        )
        paths = np.zeros((n_paths, n_steps + 1), dtype=np.float64)
        paths[:, 1:] = np.cumsum(increments, axis=1)
        return paths
