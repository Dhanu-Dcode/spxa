def __getattr__(name: str):
    if name in ("diff", "ops", "risk", "calculus"):
        import importlib

        mod = importlib.import_module(f"spxa.{name}")
        globals()[name] = mod
        return mod
    raise AttributeError(f"module '{__name__}' has no attribute '{name}'")


def __dir__():
    return sorted(list(globals().keys()) + __all__)
