def _gig_moments(lam: float, delta: float, gamma: float) -> Tuple[float, float, float, float]:
    r"""
    Compute first four raw moments of GIG(\lambda, \delta, \gamma).

    .. math::

        \mathbb{E}[Z^k] = \left(\frac{\delta}{\gamma}\right)^k \frac{K_{\lambda+k}(\delta \gamma)}{K_\lambda(\delta \gamma)}
    """
    dg = delta * gamma
    k0 = float(bessel_kv(lam, dg))
    if k0 <= 0.0 or not math.isfinite(k0):
        # Fallback for extreme parameters
        k0 = 1e-300

    scale = delta / gamma
    m1 = scale * float(bessel_kv(lam + 1.0, dg)) / k0
    m2 = (scale**2) * float(bessel_kv(lam + 2.0, dg)) / k0
    m3 = (scale**3) * float(bessel_kv(lam + 3.0, dg)) / k0
    m4 = (scale**4) * float(bessel_kv(lam + 4.0, dg)) / k0
    return m1, m2, m3, m4


def _gh_levy_measure(
    lambda_param: float, alpha: float, beta: float, delta: float
) -> DensityLevyMeasure:
    """
    Construct DensityLevyMeasure for Generalized Hyperbolic process.
    """
    gamma = math.sqrt(alpha**2 - beta**2)
    m1_z, m2_z, m3_z, m4_z = _gig_moments(lambda_param, delta, gamma)

    var_z = m2_z - m1_z**2
    mu3_z = m3_z - 3.0 * m1_z * m2_z + 2.0 * (m1_z**3)
    mu4_z = m4_z - 4.0 * m1_z * m3_z + 6.0 * (m1_z**2) * m2_z - 3.0 * (m1_z**4)
    k4_z = mu4_z - 3.0 * (var_z**2)

    # Moments of Lévy measure
    def moment_1() -> float:
        return beta * m1_z

    def moment_2() -> float:
        return m1_z + (beta**2) * var_z

    def moment_3() -> float:
        return 3.0 * beta * var_z + (beta**3) * mu3_z

    def moment_4() -> float:
        return 3.0 * var_z + 6.0 * (beta**2) * mu3_z + (beta**4) * k4_z

    # Density function evaluation
    is_nig = math.isclose(lambda_param, -0.5, abs_tol=1e-7)

    def density(x: np.ndarray) -> np.ndarray:
        out = np.zeros_like(x, dtype=float)
        nz = x != 0
        xv = x[nz]
        if is_nig:
            # Closed-form NIG density: (alpha delta / pi) * K_1(alpha sqrt(delta^2 + x^2)) / sqrt(delta^2 + x^2) * exp(beta x)
            hypot_term = np.sqrt(delta**2 + xv**2)
            k1_vals = bessel_kv(1.0, alpha * hypot_term)
            out[nz] = (alpha * delta / np.pi) * (k1_vals / hypot_term) * np.exp(beta * xv)
        else:
            # Numerical integration of normal-GIG variance mixture representation
            for idx, x_val in enumerate(xv):

                def integrand(y: float) -> float:
                    # GIG subordinator density kernel
                    gig_kernel = (y ** (lambda_param - 1.0)) * math.exp(
                        -0.5 * ((delta**2) / y + (gamma**2) * y)
                    )
                    norm_kernel = (1.0 / math.sqrt(2.0 * math.pi * y)) * math.exp(
                        -0.5 * ((x_val - beta * y) ** 2) / y
                    )
                    return gig_kernel * norm_kernel

                res, _ = integrate.quad(integrand, 1e-6, np.inf, limit=100)
                # Normalize by 2 K_lambda(delta gamma) / gamma^lambda
                norm_const = (
                    2.0 * float(bessel_kv(lambda_param, delta * gamma)) / (gamma**lambda_param)
                )
                out[np.where(nz)[0][idx]] = res / norm_const if norm_const > 0 else 0.0
        return out

    def tail(xv: float) -> float:
        res, _ = integrate.quad(lambda t: float(density(np.array([t]))[0]), xv, np.inf, limit=150)
        return res

    return DensityLevyMeasure(
        _density_fn=density,
        _total_mass=np.inf,
        _tail_fn=tail,
        _moment_fns={1: moment_1, 2: moment_2, 3: moment_3, 4: moment_4},
    )


class GeneralizedHyperbolicProcess(Process):
    r"""
    Generalized Hyperbolic (GH) Lévy Process.

    An infinitely divisible jump process whose unit-time marginal distribution is
    the five-parameter Generalized Hyperbolic distribution :math:`GH(\lambda, \alpha, \beta, \delta, \mu)`.

    Parameters
    ----------
    lambda_param : float
        Shape parameter :math:`\lambda \in \mathbb{R}` of the GIG subordinator.
        Default 1.0 (Hyperbolic process).
    alpha : float
        Tail heaviness parameter :math:`\alpha > 0`, satisfying :math:`\alpha > |\beta|`.
    beta : float
        Asymmetry / skewness parameter :math:`\beta \in (-\alpha, \alpha)`.
        Default 0.0 (symmetric).
    delta : float
        Scale parameter :math:`\delta > 0`. Default 1.0.
    mu : float
        Location / drift parameter :math:`\mu \in \mathbb{R}`. Default 0.0.

    Special Sub-Families
    --------------------
    - :math:`\lambda = -1/2`: Normal Inverse Gaussian (NIG)
    - :math:`\lambda = 1`: Hyperbolic process
    - :math:`\lambda = 0`: Variance Gamma limit

    Exactness
    ---------
    ``ExactnessLevel.EXACT``: characteristic function, cumulants, moments, and option
    pricing via Gil-Pelaez inversion are exact.
    """

    def __init__(
        self,
        lambda_param: float = 1.0,
        alpha: float = 1.5,
        beta: float = 0.0,
        delta: float = 1.0,
        mu: float = 0.0,
    ) -> None:
        if alpha <= 0.0:
            raise ValueError(f"alpha must be strictly positive, got {alpha}")
        if delta <= 0.0:
            raise ValueError(f"delta must be strictly positive, got {delta}")
        if abs(beta) >= alpha:
            raise ValueError(
                f"|beta| must be strictly less than alpha, got beta={beta}, alpha={alpha}"
            )

        self._lambda = float(lambda_param)
        self._alpha = float(alpha)
        self._beta = float(beta)
        self._delta = float(delta)
        self._mu = float(mu)
        self._gamma = math.sqrt(self._alpha**2 - self._beta**2)

        # Precompute GIG moments for cumulants
        self._m1_z, self._m2_z, self._m3_z, self._m4_z = _gig_moments(
            self._lambda, self._delta, self._gamma
        )

        subfam = self.subfamily
        node = CompositionNode(
            kind=NodeKind.PRIMITIVE,
            name=f"GH(lambda={self._lambda}, alpha={self._alpha}, beta={self._beta}, delta={self._delta}, mu={self._mu})",
            math_note=(
                f"GH({subfam}) process: γ=√(α²-β²)={self._gamma:.4f}, "
                f"κ₁={self.cumulant_exact(1):.4f}, κ₂={self.cumulant_exact(2):.4f}"
            ),
            reference="Barndorff-Nielsen (1977); Eberlein & Prause (2002)",
        )
        super().__init__(exactness=ExactnessLevel.EXACT, _node=node)

    # ------------------------------------------------------------------
    # Properties & Subfamilies
    # ------------------------------------------------------------------

    @property
    def lambda_param(self) -> float:
        r"""Shape parameter :math:`\lambda`."""
        return self._lambda

    @property
    def lam(self) -> float:
        r"""Alias for :math:`\lambda`."""
        return self._lambda

    @property
    def alpha(self) -> float:
        r"""Tail heaviness parameter :math:`\alpha > 0`."""
        return self._alpha

    @property
    def beta(self) -> float:
        r"""Asymmetry / skewness parameter :math:`\beta`."""
        return self._beta

    @property
    def delta(self) -> float:
        r"""Scale parameter :math:`\delta > 0`."""
        return self._delta

    @property
    def mu(self) -> float:
        r"""Location / drift parameter :math:`\mu`."""
        return self._mu

    @property
    def gamma(self) -> float:
        r"""Root parameter :math:`\gamma = \sqrt{\alpha^2 - \beta^2}`."""
        return self._gamma

    @property
    def subfamily(self) -> str:
        """Name of the Generalized Hyperbolic subfamily."""
        if math.isclose(self._lambda, -0.5, abs_tol=1e-7):
            return "NIG"
        if math.isclose(self._lambda, 1.0, abs_tol=1e-7):
            return "Hyperbolic"
        if math.isclose(self._lambda, 0.0, abs_tol=1e-7):
            return "Hyperbolic Cosine"
        return "General GH"

    @property
    def is_nig(self) -> bool:
        r"""True if :math:`\lambda = -1/2` (Normal Inverse Gaussian)."""
        return math.isclose(self._lambda, -0.5, abs_tol=1e-7)

    @property
    def is_hyperbolic(self) -> bool:
        r"""True if :math:`\lambda = 1` (Hyperbolic)."""
        return math.isclose(self._lambda, 1.0, abs_tol=1e-7)

    # ------------------------------------------------------------------
    # Exactness & Triplet
    # ------------------------------------------------------------------

    def _triplet(self) -> LevyTriplet:
        nu_measure = _gh_levy_measure(self._lambda, self._alpha, self._beta, self._delta)

        # Truncated drift b_drift = mu + integral_{|x| <= 1} x nu(dx)
        # Using moment_1 of truncated nu or quad integration:
        def integrand(x: float) -> float:
            if abs(x) < 1e-10:
                return 0.0
            return float(x * nu_measure.density(np.array([x]))[0])

        b_pos, _ = integrate.quad(integrand, 1e-8, 1.0, limit=150)
        b_neg, _ = integrate.quad(integrand, -1.0, -1e-8, limit=150)
        b_drift = self._mu + b_pos + b_neg

        return LevyTriplet(b=b_drift, sigma_sq=0.0, nu=nu_measure)

    def _properties(self) -> ProcessProperties:
        # Martingale iff expected drift is zero
        is_mg = math.isclose(self.cumulant_exact(1), 0.0, abs_tol=1e-10)
        return ProcessProperties(
            has_stationary_increments=True,
            has_independent_increments=True,
            is_martingale=is_mg,
            has_finite_variance=True,
            has_finite_mean=True,
            self_similarity_index=None,
            tail_index=None,
            is_subordinator=False,
            notes=[
                f"Generalized Hyperbolic ({self.subfamily}) process: lambda={self._lambda}, alpha={self._alpha}, beta={self._beta}, delta={self._delta}, mu={self._mu}.",
                f"Subordinating GIG: gamma={self._gamma:.4f}, E[Z]={self._m1_z:.4f}, Var(Z)={self._m2_z - self._m1_z**2:.4f}.",
            ],
        )

    # ------------------------------------------------------------------
    # Characteristic Function & Exponent
    # ------------------------------------------------------------------

    def char_exponent(self, u: Union[float, complex, np.ndarray]) -> np.ndarray:
        r"""
        Lévy characteristic exponent :math:`\psi(u) = \ln \mathbb{E}[e^{i u X_1}]`.

        .. math::

            \psi(u) = i \mu u + \lambda \ln\left(\frac{\gamma}{\zeta(u)}\right) + \ln K_\lambda(\delta \zeta(u)) - \ln K_\lambda(\delta \gamma)

        where :math:`\zeta(u) = \sqrt{\alpha^2 - (\beta + i u)^2}`.
        """
        u_arr = np.asarray(u, dtype=complex)
        zeta = np.sqrt(self._alpha**2 - (self._beta + 1j * u_arr) ** 2)

        # Log ratio of modified Bessel functions
        dg = self._delta * self._gamma
        k_base = float(bessel_kv(self._lambda, dg))

        # Vectorized Bessel kv over complex argument
        # Scipy kv accepts complex arguments
        k_zeta = bessel_kv(self._lambda, self._delta * zeta)

        term1 = 1j * self._mu * u_arr
        term2 = self._lambda * np.log(self._gamma / zeta)
        term3 = np.log(k_zeta / k_base)

        psi = term1 + term2 + term3
        return psi if psi.ndim > 0 else psi.item()

    def char_func(self, u: Union[float, np.ndarray], t: float = 1.0) -> np.ndarray:
        r"""
        Exact characteristic function :math:`\phi(u; t) = \mathbb{E}[e^{i u X_t}] = e^{t \psi(u)}`.
        """
        if t < 0.0:
            raise ValueError(f"Time horizon t must be non-negative, got {t}")
        psi = self.char_exponent(u)
        return np.exp(t * psi)

    def char_func_exact(self, u: Union[float, np.ndarray], t: float = 1.0) -> np.ndarray:
        """Alias for char_func."""
        return self.char_func(u, t=t)

    # ------------------------------------------------------------------
    # Cumulants & Moments
    # ------------------------------------------------------------------

    def cumulant_exact(self, order: int, t: float = 1.0) -> float:
        r"""
        Exact closed-form cumulant :math:`\kappa_n(t) = t \kappa_n(1)`.

        Closed forms:
        - :math:`\kappa_1 = \mu + \beta \mathbb{E}[Z]`
        - :math:`\kappa_2 = \mathbb{E}[Z] + \beta^2 \mathrm{Var}(Z)`
        - :math:`\kappa_3 = 3 \beta \mathrm{Var}(Z) + \beta^3 \mu_3(Z)`
        - :math:`\kappa_4 = 3 \mathrm{Var}(Z) + 6 \beta^2 \mu_3(Z) + \beta^4 (\mu_4(Z) - 3 \mathrm{Var}(Z)^2)`
        """
        if order < 1:
            raise ValueError(f"Cumulant order must be >= 1, got {order}")
        if t < 0.0:
            raise ValueError(f"Time t must be non-negative, got {t}")

        m1_z, m2_z, m3_z, m4_z = self._m1_z, self._m2_z, self._m3_z, self._m4_z
        var_z = m2_z - m1_z**2
        mu3_z = m3_z - 3.0 * m1_z * m2_z + 2.0 * (m1_z**3)
        mu4_z = m4_z - 4.0 * m1_z * m3_z + 6.0 * (m1_z**2) * m2_z - 3.0 * (m1_z**4)
        k4_z = mu4_z - 3.0 * (var_z**2)

        beta = self._beta

        if order == 1:
            k1 = self._mu + beta * m1_z
            return float(t * k1)
        elif order == 2:
            k2 = m1_z + (beta**2) * var_z
            return float(t * k2)
        elif order == 3:
            k3 = 3.0 * beta * var_z + (beta**3) * mu3_z
            return float(t * k3)
        elif order == 4:
            k4 = 3.0 * var_z + 6.0 * (beta**2) * mu3_z + (beta**4) * k4_z
            return float(t * k4)
        else:
            # High-order numerical differentiation of psi(u) at u=0
            h = 1e-4

            # 5-point complex derivative
            def psi_fn(u_val: float) -> complex:
                return complex(self.char_exponent(u_val))

            pts = np.array([-2, -1, 1, 2]) * h
            vals = [psi_fn(p) for p in pts]
            # First derivative approx
            d_val = (-vals[3] + 8.0 * vals[2] - 8.0 * vals[1] + vals[0]) / (12.0 * h)
            return float(t * np.imag(d_val))

    def cumulants(self, order: int = 4, t: float = 1.0) -> Dict[int, float]:
        """Dictionary of exact cumulants {1: κ_1, ..., order: κ_order}."""
        return {n: self.cumulant_exact(n, t=t) for n in range(1, order + 1)}

    # ------------------------------------------------------------------
    # Drift Compensator & Option Pricing
    # ------------------------------------------------------------------

    def drift_compensator(self) -> float:
        r"""
        Martingale drift compensator :math:`\omega = -\psi(-i) = -\ln \mathbb{E}[e^{X_1}]`.

        Ensures :math:`S_t = S_0 \exp((r - q + \omega)t + X_t)` satisfies
        :math:`\mathbb{E}[S_t] = S_0 e^{(r - q)t}`.
        Requires :math:`\alpha > |\beta + 1|`.
        """
        if self._alpha <= abs(self._beta + 1.0):
            raise ValueError(
                f"Moment condition failed: alpha ({self._alpha}) must be strictly greater "
                f"than |beta + 1| ({abs(self._beta + 1.0)}) for exponential moment E[e^{{X_1}}] to exist."
            )
        psi_val = complex(self.char_exponent(-1j))
        return float(-psi_val.real)

    def call_price(
        self,
        K: Union[float, np.ndarray],
        T: float = 1.0,
        r: float = 0.0,
        q: float = 0.0,
        s0: float = 100.0,
    ) -> Union[float, np.ndarray]:
        r"""
        European call option price via Gil-Pelaez Fourier inversion.
        """
        omega = self.drift_compensator()
        drift = (r - q + omega) * T

        def phi_log_s(u: complex) -> complex:
            return np.exp(1j * u * drift) * np.exp(T * self.char_exponent(u))

        phi_minus_i = phi_log_s(-1j)

        def _price_single(strike: float) -> float:
            k_log = math.log(strike / s0)

            def integrand1(u: float) -> float:
                if u == 0.0:
                    return 0.0
                val = (phi_log_s(u - 1j) * np.exp(-1j * u * k_log)) / (1j * u * phi_minus_i)
                return float(val.real)

            def integrand2(u: float) -> float:
                if u == 0.0:
                    return 0.0
                val = (phi_log_s(u) * np.exp(-1j * u * k_log)) / (1j * u)
                return float(val.real)

            res1, _ = integrate.quad(integrand1, 1e-8, 100.0, limit=200)
            res2, _ = integrate.quad(integrand2, 1e-8, 100.0, limit=200)

            pi1 = 0.5 + res1 / math.pi
            pi2 = 0.5 + res2 / math.pi

            c = s0 * math.exp(-q * T) * pi1 - strike * math.exp(-r * T) * pi2
            intrinsic = max(0.0, s0 * math.exp(-q * T) - strike * math.exp(-r * T))
            return float(max(intrinsic, c))

        K_arr = np.asarray(K)
        if K_arr.ndim == 0:
            return _price_single(float(K_arr))
        return np.array([_price_single(float(k)) for k in K_arr], dtype=float)

    def put_price(
        self,
        K: Union[float, np.ndarray],
        T: float = 1.0,
        r: float = 0.0,
        q: float = 0.0,
        s0: float = 100.0,
    ) -> Union[float, np.ndarray]:
        r"""
        European put option price via Put-Call parity.
        """
        calls = self.call_price(K, T=T, r=r, q=q, s0=s0)
        df_r = math.exp(-r * T)
        df_q = math.exp(-q * T)
        K_arr = np.asarray(K, dtype=float)
        puts = calls - s0 * df_q + K_arr * df_r
        intrinsic = np.maximum(0.0, K_arr * df_r - s0 * df_q)
        return np.maximum(puts, intrinsic)

    def implied_volatility(
        self,
        K: Union[float, np.ndarray],
        T: float = 1.0,
        r: float = 0.0,
        q: float = 0.0,
        s0: float = 100.0,
    ) -> Union[float, np.ndarray]:
        r"""
        Black-Scholes implied volatility inverted from European call price.
        """
        calls = self.call_price(K, T=T, r=r, q=q, s0=s0)

        def _bs_call(s: float, k: float, t: float, r_: float, q_: float, sigma: float) -> float:
            if sigma <= 1e-8:
                return max(0.0, s * math.exp(-q_ * t) - k * math.exp(-r_ * t))
            d1 = (math.log(s / k) + (r_ - q_ + 0.5 * sigma**2) * t) / (sigma * math.sqrt(t))
            d2 = d1 - sigma * math.sqrt(t)
            from scipy.stats import norm  # type: ignore[import-untyped]

            return s * math.exp(-q_ * t) * float(norm.cdf(d1)) - k * math.exp(-r_ * t) * float(
                norm.cdf(d2)
            )

        def _iv_single(k: float, target_call: float) -> float:
            intrinsic = max(0.0, s0 * math.exp(-q * T) - k * math.exp(-r * T))
            if target_call <= intrinsic + 1e-9:
                return 1e-4

            def obj(sig: float) -> float:
                return _bs_call(s0, k, T, r, q, sig) - target_call

            try:
                sol = optimize.brentq(obj, 1e-4, 5.0, xtol=1e-6)
                return float(sol)
            except Exception:
                return float("nan")

        K_arr = np.asarray(K)
        if K_arr.ndim == 0:
            return _iv_single(float(K_arr), float(calls))
        return np.array(
            [_iv_single(float(k), float(c)) for k, c in zip(K_arr, np.asarray(calls))], dtype=float
        )

    # ------------------------------------------------------------------
    # Simulation
    # ------------------------------------------------------------------

    def simulate(
        self,
        n_steps: int = 100,
        dt: Optional[float] = None,
        time_horizon: Optional[float] = None,
        n_paths: int = 1,
        rng: Optional[np.random.Generator] = None,
        T: Optional[float] = None,
    ) -> np.ndarray:
        r"""
        Simulate sample paths of the Generalized Hyperbolic process :math:`X_t`.
        """
        horizon = T if T is not None else time_horizon
        from spxa.sim.exact import sample_gh

        return sample_gh(
            lambda_param=self._lambda,
            alpha=self._alpha,
            beta=self._beta,
            delta=self._delta,
            mu=self._mu,
            dt=dt,
            n_steps=n_steps,
            n_paths=n_paths,
            T=horizon,
            rng=rng,
        )

    def __repr__(self) -> str:
        return (
            f"GeneralizedHyperbolicProcess(lambda_param={self._lambda}, "
            f"alpha={self._alpha}, beta={self._beta}, delta={self._delta}, mu={self._mu})"
        )


