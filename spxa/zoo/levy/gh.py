"""
Generalized Hyperbolic (GH) Lévy Process.

An infinite-activity pure-jump Lévy process generated by the Generalized Hyperbolic
distribution. Introduced by Ole Barndorff-Nielsen (1977) and applied to financial
modeling by Eberlein & Prause (2002) and Hammerstein (2003).

The GH distribution is a normal variance-mean mixture where the mixing distribution
is the Generalized Inverse Gaussian (GIG) distribution:
    X = μ + β Z + √Z W
where W ~ N(0, 1) and Z ~ GIG(λ, δ, γ) with γ = √(α² - β²).

The class of Generalized Hyperbolic processes encompasses कई key financial models as
special or limiting cases:
    - λ = -1/2: Normal Inverse Gaussian (NIG) process (Barndorff-Nielsen 1997)
    - λ = 1: Hyperbolic distribution and process (Eberlein & Keller 1995)
    - λ > 0, δ → 0: Variance Gamma (VG) process (Madan & Seneta 1990)
    - α → ∞, δ → ∞ with δ/α → σ²: Brownian motion with drift

Characteristic function:
    φ(u; t) = exp(t · ψ(u))
    ψ(u) = i μ u + λ ln(γ / ζ(u)) + ln(K_λ(δ ζ(u))) - ln(K_λ(δ γ))
where ζ(u) = √(α² - (β + i u)²), and K_λ is the modified Bessel function of the second kind.

References
----------
Barndorff-Nielsen, O. E. (1977). Exponentially decreasing distributions and
    the normal distribution. Proceedings of the Royal Society of London.
    Series A, 353(1674), 401–419.
Barndorff-Nielsen, O. E. & Halgreen, C. (1977). Infinite divisibility of the
    hyperbolic and generalized inverse Gaussian distributions. Z. Wahrscheinlichkeit,
    38, 309–312.
Eberlein, E. & Prause, K. (2002). The generalized hyperbolic model: Financial
    derivatives and risk measures. Mathematical Finance — Bachelier Congress 2000,
    245–267.
Hammerstein, E. A. v. (2003). Generalized Hyperbolic Distributions: Theory and
    Applications to CDO Pricing. PhD thesis, University of Freiburg.
"""

