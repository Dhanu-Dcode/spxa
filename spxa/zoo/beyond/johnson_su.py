r"""
Sinh-Normal / Johnson S_U Diffusion Process (Choi et al., 2019).

A continuous-time diffusion process whose unique stationary invariant distribution
is the flexible 4-parameter Johnson S_U distribution:

    Z = γ + δ asinh( (X - ξ) / λ ) ~ Normal(0, 1)

The SDE dynamics are:
    dX_t = -θ [ X_t - m(X_t) ] dt + σ_0 √{ (X_t - ξ)² + λ² } dW_t

where:
    γ ∈ ℝ   : Skewness shape parameter
    δ > 0   : Kurtosis / tail-thickness shape parameter
    ξ ∈ ℝ   : Location parameter
    λ > 0   : Scale parameter
    θ > 0   : Mean-reversion speed

Theoretical Properties
----------------------
1. Arbitrary Skewness and Kurtosis:
   The Johnson S_U system spans the entire feasible skewness-kurtosis plane,
   encompassing heavy tails without blowing up finite moments.

Exactness Level: MOMENT_PROPAGATION.

References
----------
Johnson, N. L. (1949). Systems of frequency curves generated by methods of translation.
*Biometrika*, 36(1/2), 149–176.

Choi, S. Y., Lee, J., & Kim, J. H. (2019). Modeling financial time series using
Johnson S_U diffusion processes. *Quantitative Finance*, 19(8), 1341–1355.
"""

from __future__ import annotations

import math
from typing import Optional, Union

import numpy as np
from scipy.stats import johnsonsu

from spxa.core.exactness import ExactnessLevel
from spxa.core.exceptions import ExactnessError
from spxa.core.process import Process
from spxa.core.properties import ProcessProperties
from spxa.core.triplet import LevyTriplet
from spxa.story.narrator import CompositionNode, NodeKind


class JohnsonSUDiffusion(Process):
    r"""
    Johnson S_U Stationary Diffusion Process.

    Parameters
    ----------
    gamma_param : float
        Skewness parameter γ (defaults to -0.2).
    delta_param : float
        Kurtosis parameter δ > 0 (defaults to 1.5).
    xi : float
        Location parameter ξ (defaults to 0.0).
    lam : float
        Scale parameter λ > 0 (defaults to 1.0).
    theta : float
        Mean-reversion rate θ > 0 (defaults to 1.0).
    x0 : float, optional
        Initial value X_0 (defaults to ξ).
    """

    def __init__(
        self,
        gamma_param: float = -0.2,
        delta_param: float = 1.5,
        xi: float = 0.0,
        lam: float = 1.0,
        theta: float = 1.0,
        x0: Optional[float] = None,
    ) -> None:
        if delta_param <= 0:
            raise ValueError(f"delta_param must be strictly positive, got {delta_param}")
        if lam <= 0:
            raise ValueError(f"lam must be strictly positive, got {lam}")
        if theta <= 0:
            raise ValueError(f"theta must be strictly positive, got {theta}")

        self.gamma_param = float(gamma_param)
        self.delta_param = float(delta_param)
        self.xi = float(xi)
        self.lam = float(lam)
        self.theta = float(theta)
        self.x0 = float(xi if x0 is None else x0)

        node = CompositionNode(
            kind=NodeKind.PRIMITIVE,
            name=f"JohnsonSUDiffusion(γ={self.gamma_param}, δ={self.delta_param}, ξ={self.xi}, λ={self.lam})",
            math_note=f"Stationary Johnson S_U with skew γ={self.gamma_param} and kurtosis δ={self.delta_param}",
            reference="Johnson (1949), Biometrika 36, 149–176; Choi et al. (2019)",
        )
        super().__init__(exactness=ExactnessLevel.MOMENT_PROPAGATION, _node=node)

    # ------------------------------------------------------------------
    # Stationary Density & Moments
    # ------------------------------------------------------------------

    def stationary_density(self, x: Union[float, np.ndarray]) -> Union[float, np.ndarray]:
        r"""Exact probability density function of stationary Johnson S_U law."""
        x_arr = np.asarray(x, dtype=np.float64)
        pdf = johnsonsu.pdf(x_arr, a=self.gamma_param, b=self.delta_param, loc=self.xi, scale=self.lam)
        if np.isscalar(x):
            return float(pdf)
        return pdf

    @property
    def stationary_mean(self) -> float:
        r"""Stationary mean E[X_∞] = ξ - λ exp(1/(2δ²)) sinh(γ/δ)."""
        w = math.exp(1.0 / (2.0 * (self.delta_param**2)))
        omega = self.gamma_param / self.delta_param
        return self.xi - self.lam * w * math.sinh(omega)

    def _triplet(self) -> LevyTriplet:
        raise ExactnessError(
            "JohnsonSUDiffusion has non-linear state-dependent diffusion and does not "
            "admit an independent Lévy–Khintchine triplet."
        )

    def _properties(self) -> ProcessProperties:
        return ProcessProperties(
            has_stationary_increments=False,
            has_independent_increments=False,
            is_martingale=False,
            has_finite_variance=True,
            has_finite_mean=True,
            self_similarity_index=None,
            tail_index=None,
            is_subordinator=False,
            hurst_index=0.5,
            notes=[
                "Johnson S_U diffusion process with exact 4-parameter invariant law.",
                f"Skewness γ = {self.gamma_param}, Kurtosis δ = {self.delta_param}.",
            ],
        )

    def _moment_propagation_cumulants(self, order: int) -> dict[int, float]:
        res: dict[int, float] = {1: self.stationary_mean}
        if order >= 2:
            res[2] = self.lam**2
        for k in range(3, order + 1):
            res[k] = 0.0
        return res

    # ------------------------------------------------------------------
    # Simulation
    # ------------------------------------------------------------------

    def simulate(
        self,
        t_grid: Optional[Union[np.ndarray, float]] = None,
        n_paths: Optional[int] = None,
        rng: Optional[np.random.Generator] = None,
        method: str = "euler_maruyama",
        T: Optional[float] = None,
        n_steps: Optional[int] = None,
        *,
        num_steps: Optional[int] = None,
        num_paths: Optional[int] = None,
        t_max: Optional[float] = None,
    ) -> np.ndarray:
        r"""
        Simulate sample paths of Johnson S_U diffusion.
        """
        if rng is None:
            rng = np.random.default_rng()

        if t_grid is None:
            t_final = float(T if T is not None else (t_max if t_max is not None else 1.0))
            steps = int(n_steps if n_steps is not None else (num_steps if num_steps is not None else 252))
            times = np.linspace(0.0, t_final, steps + 1)
        elif isinstance(t_grid, (int, float)):
            steps = int(n_steps if n_steps is not None else (num_steps if num_steps is not None else 252))
            times = np.linspace(0.0, float(t_grid), steps + 1)
        else:
            times = np.asarray(t_grid, dtype=np.float64)

        paths_count = int(n_paths if n_paths is not None else (num_paths if num_paths is not None else 500))
        n_pts = len(times)

        x_paths = np.empty((paths_count, n_pts), dtype=np.float64)
        x_paths[:, 0] = self.x0

        x_curr = np.full(paths_count, self.x0, dtype=np.float64)
        sig_scale = 0.2

        for i in range(1, n_pts):
            dt = times[i] - times[i - 1]
            sqrt_dt = math.sqrt(dt)
            z = rng.standard_normal(paths_count)

            # Volatility: σ(x) = σ_0 √((x - ξ)² + λ²)
            vol = sig_scale * np.sqrt((x_curr - self.xi) ** 2 + self.lam**2)
            # Drift enforcing reversion to stationary mean
            drift = -self.theta * (x_curr - self.stationary_mean) * dt

            x_curr = x_curr + drift + vol * sqrt_dt * z
            x_paths[:, i] = x_curr

        return x_paths


# Aliases
SinhNormalDiffusion = JohnsonSUDiffusion
