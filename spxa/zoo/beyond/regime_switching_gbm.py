"""
Regime-Switching Geometric Brownian Motion (RS-GBM).

Continuous-time Markov-modulated Black-Scholes diffusion introduced by
Hamilton (1989), Naik (1993), Guo (2001), and Elliott, Aggoun, & Moore (1994).

Model Dynamics:
    dS_t = μ(Y_t) S_t dt + σ(Y_t) S_t dW_t,   S_0 > 0
    X_t = ln(S_t / S_0):
    dX_t = (μ(Y_t) - 0.5 σ(Y_t)²) dt + σ(Y_t) dW_t

where:
    - Y_t ∈ {0, 1, ..., K-1} is a continuous-time Markov chain (CTMC) with
      infinitesimal generator matrix Q = (q_{ij})_{i,j=0}^{K-1}
    - μ = (μ_0, ..., μ_{K-1}) are regime-dependent drift rates
    - σ = (σ_0, ..., σ_{K-1}) are regime-dependent volatilities (σ_i > 0)
    - W_t is a standard 1D Brownian motion independent of Y_t

Analytical Tractability via Matrix Exponentials:
    - Transition probability matrix: P(t) = exp(Q t)
    - Conditional moments: E[S_t^n | S_0, Y_0 = i] = S_0^n ∑_j [exp(M_n t)]_{ij}
      where M_n = Q + diag(n μ + 0.5 n(n - 1) σ²)
    - Exact continuous characteristic function:
      φ(u; t | Y_0 = i) = ∑_j [exp((Q + diag(ψ(u))) t)]_{ij}
      where ψ_i(u) = i u (μ_i - 0.5 σ_i²) - 0.5 u² σ_i²
    - European options priced in closed-form via Gil-Pelaez Fourier inversion.
    - Exact coupled Markov-jump and diffusion simulation.

References
----------
Hamilton, J. D. (1989). A new approach to the economic analysis of nonstationary
    time series and the business cycle. Econometrica, 57(2), 357–384.
Naik, V. (1993). Option valuation and hedging in a regime switching framework.
    The Journal of Finance, 48(5), 1969–1997.
Guo, X. (2001). Information and option pricings. Quantitative Finance, 1(1), 38–44.
Elliott, R. J., Aggoun, L., & Moore, J. B. (1994). Hidden Markov Models:
    Estimation and Control. Springer-Verlag.
"""

from __future__ import annotations

import math
from typing import Optional, Union, Tuple, Sequence

import numpy as np
from scipy import linalg as la, integrate  # type: ignore[import-untyped]

from spxa.core.exactness import ExactnessLevel
from spxa.core.exceptions import ExactnessError
from spxa.core.process import Process
from spxa.core.properties import ProcessProperties
from spxa.core.triplet import LevyTriplet
from spxa.story.narrator import CompositionNode, NodeKind


class RegimeSwitchingGBM(Process):
    r"""
    Regime-Switching Geometric Brownian Motion (RS-GBM).

    .. math::

        dS_t = \mu(Y_t) S_t dt + \sigma(Y_t) S_t dW_t, \quad S_0 > 0

    where :math:`Y_t \in \{0, 1, \dots, K-1\}` is a Markov chain generated by rate matrix :math:`Q`.

    Parameters
    ----------
    mu : Sequence[float] or np.ndarray
        Drifts in each regime, length :math:`K`. Default ``(0.08, -0.04)``.
    sigma : Sequence[float] or np.ndarray
        Volatilities in each regime, length :math:`K`. Default ``(0.15, 0.35)``.
    transition_rates : Sequence[Sequence[float]] or np.ndarray, optional
        Generator matrix :math:`Q` of size :math:`K \times K`. Default 2-state with
        :math:`\lambda_{01} = 0.5, \lambda_{10} = 1.0`.
    s0 : float
        Initial asset price :math:`S_0 > 0`. Default 100.0.
    initial_regime : int
        Initial regime :math:`Y_0 \in \{0, \dots, K-1\}`. Default 0.
    """

    def __init__(
        self,
        mu: Sequence[float] = (0.08, -0.04),
        sigma: Sequence[float] = (0.15, 0.35),
        transition_rates: Optional[Union[Sequence[Sequence[float]], np.ndarray]] = None,
        s0: float = 100.0,
        initial_regime: int = 0,
    ) -> None:
        mu_arr = np.asarray(mu, dtype=float)
        sigma_arr = np.asarray(sigma, dtype=float)

        if mu_arr.ndim != 1:
            raise ValueError(f"Drift 'mu' must be 1D, got shape {mu_arr.shape}")
        if sigma_arr.ndim != 1:
            raise ValueError(f"Volatility 'sigma' must be 1D, got shape {sigma_arr.shape}")
        if len(mu_arr) != len(sigma_arr):
            raise ValueError(
                f"Length of 'mu' ({len(mu_arr)}) must match 'sigma' ({len(sigma_arr)})"
            )
        if len(mu_arr) < 2:
            raise ValueError(f"Number of regimes must be >= 2, got {len(mu_arr)}")
        if np.any(sigma_arr <= 0.0):
            raise ValueError(f"All volatilities must be strictly positive, got {sigma_arr}")
        if s0 <= 0.0:
            raise ValueError(f"Initial asset price 's0' must be strictly positive, got {s0}")

        k_states = len(mu_arr)
        if not (0 <= initial_regime < k_states):
            raise ValueError(f"initial_regime must be in [0, {k_states - 1}], got {initial_regime}")

        if transition_rates is None:
            if k_states != 2:
                raise ValueError("transition_rates must be provided when n_regimes != 2")
            q_mat = np.array([[-0.5, 0.5], [1.0, -1.0]], dtype=float)
        else:
            q_mat = np.asarray(transition_rates, dtype=float)
            if q_mat.shape != (k_states, k_states):
                raise ValueError(
                    f"transition_rates matrix must be ({k_states}, {k_states}), got {q_mat.shape}"
                )
            # Verify generator rows sum to 0
            if not np.allclose(np.sum(q_mat, axis=1), 0.0, atol=1e-8):
                raise ValueError("Generator matrix Q rows must sum to zero")

        self._mu = mu_arr
        self._sigma = sigma_arr
        self._q = q_mat
        self._s0 = float(s0)
        self._initial_regime = int(initial_regime)
        self._n_regimes = k_states

        # Stationary distribution pi * Q = 0
        w, v = la.eig(self._q.T)
        zero_idx = np.isclose(w, 0.0)
        if np.any(zero_idx):
            pi = v[:, zero_idx][:, 0].real
            pi = pi / np.sum(pi)
            self._stationary_pi = np.maximum(pi, 0.0)
            self._stationary_pi /= np.sum(self._stationary_pi)
        else:
            self._stationary_pi = np.full(self._n_regimes, 1.0 / self._n_regimes)

        node = CompositionNode(
            kind=NodeKind.PRIMITIVE,
            name=f"RegimeSwitchingGBM(K={self._n_regimes}, S0={self._s0:.2f})",
            math_note=f"K={self._n_regimes} states, initial state Y0={self._initial_regime}",
            reference="Hamilton (1989); Naik (1993); Guo (2001)",
        )
        super().__init__(exactness=ExactnessLevel.MOMENT_PROPAGATION, _node=node)

    # ------------------------------------------------------------------
    # Properties
    # ------------------------------------------------------------------

    @property
    def n_regimes(self) -> int:
        """Number of regimes :math:`K`."""
        return self._n_regimes

    @property
    def mu(self) -> np.ndarray:
        """Array of regime drifts :math:`\\boldsymbol{\\mu}`."""
        return self._mu.copy()

    @property
    def sigma(self) -> np.ndarray:
        """Array of regime volatilities :math:`\\boldsymbol{\\sigma}`."""
        return self._sigma.copy()

    @property
    def generator_matrix(self) -> np.ndarray:
        """Infinitesimal generator matrix :math:`Q`."""
        return self._q.copy()

    @property
    def Q(self) -> np.ndarray:
        """Alias for generator_matrix."""
        return self._q.copy()

    @property
    def s0(self) -> float:
        """Initial spot price :math:`S_0 > 0`."""
        return self._s0

    @property
    def initial_regime(self) -> int:
        """Initial regime index :math:`Y_0`."""
        return self._initial_regime

    @property
    def stationary_distribution(self) -> np.ndarray:
        r"""Stationary probability vector :math:`\boldsymbol{\pi}`."""
        return self._stationary_pi.copy()

    # ------------------------------------------------------------------
    # Exactness & Triplet
    # ------------------------------------------------------------------

    def _triplet(self) -> LevyTriplet:
        raise ExactnessError(
            method="triplet",
            required="EXACT",
            actual="MOMENT_PROPAGATION",
            reason=(
                "RegimeSwitchingGBM is a Markov-modulated diffusion with state-dependent parameters "
                "driven by a continuous-time Markov chain, violating the stationary and independent "
                "increments condition of pure Levy processes. Exact matrix exponential moments, "
                "characteristic functions, option pricing, and path simulation are available directly."
            ),
        )

    def _properties(self) -> ProcessProperties:
        return ProcessProperties(
            has_stationary_increments=False,
            has_independent_increments=False,
            is_martingale=False,
            has_finite_mean=True,
            has_finite_variance=True,
            is_subordinator=False,
            notes=[
                f"Regime-Switching Geometric Brownian Motion with {self._n_regimes} regimes.",
                f"Drifts: {self._mu}, Volatilities: {self._sigma}.",
            ],
        )

    # ------------------------------------------------------------------
    # Transition Probabilities & Matrix Exponential Moments
    # ------------------------------------------------------------------

    def transition_probabilities(self, t: float = 1.0) -> np.ndarray:
        r"""
        Exact transition probability matrix :math:`P(t) = \exp(Q t)`.
        """
        if t < 0.0:
            raise ValueError(f"Time t must be non-negative, got {t}")
        return la.expm(self._q * t)

    def conditional_moment(
        self, n: int = 1, t: float = 1.0, initial_regime: Optional[int] = None
    ) -> float:
        r"""
        Exact :math:`n`-th moment :math:`\mathbb{E}[S_t^n \mid S_0, Y_0]`.

        .. math::

            M_n = Q + \mathrm{diag}\left(n \mu + \frac{1}{2} n(n - 1) \sigma^2\right) \\
            \mathbb{E}[S_t^n \mid S_0, Y_0 = i] = S_0^n \sum_j [\exp(M_n t)]_{ij}
        """
        if n < 1:
            raise ValueError(f"Moment order n must be >= 1, got {n}")
        if t < 0.0:
            raise ValueError(f"Time t must be non-negative, got {t}")

        reg = self._initial_regime if initial_regime is None else int(initial_regime)
        if not (0 <= reg < self._n_regimes):
            raise ValueError(f"Invalid regime {reg}")

        diag_terms = float(n) * self._mu + 0.5 * float(n * (n - 1)) * (self._sigma**2)
        m_n = self._q + np.diag(diag_terms)
        exp_m = la.expm(m_n * t)
        return float((self._s0**n) * np.sum(exp_m[reg, :]))

    def conditional_mean(self, t: float = 1.0, initial_regime: Optional[int] = None) -> float:
        """Exact conditional expectation :math:`\\mathbb{E}[S_t \\mid S_0, Y_0]`."""
        return self.conditional_moment(n=1, t=t, initial_regime=initial_regime)

    def conditional_second_moment(
        self, t: float = 1.0, initial_regime: Optional[int] = None
    ) -> float:
        """Exact conditional second moment :math:`\\mathbb{E}[S_t^2 \\mid S_0, Y_0]`."""
        return self.conditional_moment(n=2, t=t, initial_regime=initial_regime)

    def conditional_variance(self, t: float = 1.0, initial_regime: Optional[int] = None) -> float:
        r"""
        Exact conditional variance :math:`\mathrm{Var}(S_t \mid S_0, Y_0) = \mathbb{E}[S_t^2] - (\mathbb{E}[S_t])^2`.
        """
        m1 = self.conditional_mean(t=t, initial_regime=initial_regime)
        m2 = self.conditional_second_moment(t=t, initial_regime=initial_regime)
        return float(max(0.0, m2 - m1**2))

    def conditional_std(self, t: float = 1.0, initial_regime: Optional[int] = None) -> float:
        """Exact conditional standard deviation."""
        return math.sqrt(self.conditional_variance(t=t, initial_regime=initial_regime))

    # ------------------------------------------------------------------
    # Characteristic Function
    # ------------------------------------------------------------------

    def char_func(
        self,
        u: Union[float, complex, np.ndarray],
        t: float = 1.0,
        initial_regime: Optional[int] = None,
    ) -> np.ndarray:
        r"""
        Exact characteristic function :math:`\phi(u; t \mid Y_0) = \mathbb{E}[e^{i u \ln(S_t / S_0)} \mid Y_0]`.

        .. math::

            M_{\mathrm{char}}(u) = Q + \mathrm{diag}\left( i u (\mu - \frac{1}{2}\sigma^2) - \frac{1}{2} u^2 \sigma^2 \right) \\
            \phi(u; t \mid Y_0 = i) = \sum_j [\exp(M_{\mathrm{char}}(u) t)]_{ij}
        """
        if t < 0.0:
            raise ValueError(f"Time t must be non-negative, got {t}")
        u_arr = np.asarray(u, dtype=complex)
        reg = self._initial_regime if initial_regime is None else int(initial_regime)
        if not (0 <= reg < self._n_regimes):
            raise ValueError(f"Invalid regime {reg}")

        if t == 0.0:
            res = np.ones_like(u_arr, dtype=complex)
            return res if res.ndim > 0 else res.item()

        def _eval_single(u_val: complex) -> complex:
            psi = 1j * u_val * (self._mu - 0.5 * (self._sigma**2)) - 0.5 * (u_val**2) * (
                self._sigma**2
            )
            m_char = self._q + np.diag(psi)
            exp_m = la.expm(m_char * t)
            return complex(np.sum(exp_m[reg, :]))

        vec_func = np.vectorize(_eval_single)
        res = vec_func(u_arr)
        return res if res.ndim > 0 else res.item()

    # ------------------------------------------------------------------
    # European Option Pricing (Gil-Pelaez Inversion)
    # ------------------------------------------------------------------

    def call_price(
        self,
        strike: float,
        time_to_maturity: float = 1.0,
        discount_rate: Optional[float] = None,
        initial_regime: Optional[int] = None,
    ) -> float:
        r"""
        European call option price via Gil-Pelaez Fourier inversion.
        """
        if strike <= 0.0:
            raise ValueError(f"Strike must be strictly positive, got {strike}")
        if time_to_maturity <= 0.0:
            return float(max(0.0, self._s0 - strike))

        tau = time_to_maturity
        r_rate = self._mu[0] if discount_rate is None else discount_rate
        k_log = math.log(strike / self._s0)

        cf_minus_i = self.char_func(-1j, t=tau, initial_regime=initial_regime)

        def _p1_integrand(u: float) -> float:
            if u == 0.0:
                return 0.0
            num = np.exp(-1j * u * k_log) * self.char_func(
                u - 1j, t=tau, initial_regime=initial_regime
            )
            denom = 1j * u * cf_minus_i
            return float((num / denom).real)

        def _p2_integrand(u: float) -> float:
            if u == 0.0:
                return 0.0
            num = np.exp(-1j * u * k_log) * self.char_func(u, t=tau, initial_regime=initial_regime)
            denom = 1j * u
            return float((num / denom).real)

        i1, _ = integrate.quad(_p1_integrand, 1e-7, 100.0, limit=200)
        i2, _ = integrate.quad(_p2_integrand, 1e-7, 100.0, limit=200)

        p1 = 0.5 + i1 / math.pi
        p2 = 0.5 + i2 / math.pi

        forward = float(self.conditional_mean(t=tau, initial_regime=initial_regime))
        disc = math.exp(-r_rate * tau)

        call_val = disc * (forward * p1 - strike * p2)
        return float(max(0.0, call_val))

    def put_price(
        self,
        strike: float,
        time_to_maturity: float = 1.0,
        discount_rate: Optional[float] = None,
        initial_regime: Optional[int] = None,
    ) -> float:
        r"""
        European put option price via Put-Call parity.
        """
        r_rate = self._mu[0] if discount_rate is None else discount_rate
        call = self.call_price(
            strike=strike,
            time_to_maturity=time_to_maturity,
            discount_rate=r_rate,
            initial_regime=initial_regime,
        )
        forward = float(self.conditional_mean(t=time_to_maturity, initial_regime=initial_regime))
        disc = math.exp(-r_rate * time_to_maturity)
        put_val = call - disc * (forward - strike)
        return float(max(0.0, put_val))

    # ------------------------------------------------------------------
    # Simulation
    # ------------------------------------------------------------------

    def simulate(
        self,
        n_steps: int = 100,
        dt: Optional[float] = None,
        time_horizon: Optional[float] = None,
        n_paths: int = 1,
        rng: Optional[np.random.Generator] = None,
    ) -> np.ndarray:
        """Simulate sample paths of asset price :math:`S_t`."""
        from spxa.sim.exact import sample_regime_switching_gbm

        return sample_regime_switching_gbm(
            mu=self._mu,
            sigma=self._sigma,
            transition_rates=self._q,
            s0=self._s0,
            initial_regime=self._initial_regime,
            dt=dt,
            n_steps=n_steps,
            n_paths=n_paths,
            T=time_horizon,
            rng=rng,
            return_regimes=False,
        )

    def simulate_joint(
        self,
        n_steps: int = 100,
        dt: Optional[float] = None,
        time_horizon: Optional[float] = None,
        n_paths: int = 1,
        rng: Optional[np.random.Generator] = None,
    ) -> Tuple[np.ndarray, np.ndarray]:
        """Simulate coupled paths of asset price :math:`S_t` and regime states :math:`Y_t`."""
        from spxa.sim.exact import sample_regime_switching_gbm

        return sample_regime_switching_gbm(
            mu=self._mu,
            sigma=self._sigma,
            transition_rates=self._q,
            s0=self._s0,
            initial_regime=self._initial_regime,
            dt=dt,
            n_steps=n_steps,
            n_paths=n_paths,
            T=time_horizon,
            rng=rng,
            return_regimes=True,
        )

    def __repr__(self) -> str:
        return (
            f"RegimeSwitchingGBM(n_regimes={self._n_regimes}, s0={self._s0}, "
            f"initial_regime={self._initial_regime})"
        )


