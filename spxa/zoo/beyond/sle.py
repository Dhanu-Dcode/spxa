r"""
Schramm–Loewner Evolution (SLE_κ) (Schramm, 2000).

A family of conformally invariant random planar fractal curves γ(t) in the
upper half-plane ℍ = {z ∈ ℂ : Im(z) > 0} generated by the Loewner differential
equation driven by a one-dimensional Brownian motion:

    ∂_t g_t(z) = 2 / [ g_t(z) - √κ B_t ],   g_0(z) = z

where:
    κ > 0 : Dimension parameter governing path roughness
    B_t   : Standard 1-dimensional Brownian motion driving the conformal slit

Theoretical Properties
----------------------
1. Fractal Hausdorff Dimension (Beffara, 2008):
   The Hausdorff dimension of the SLE_κ curve is:
       d_f = min( 2, 1 + κ / 8 )

2. Three Geometric Regimes:
   - 0 < κ ≤ 4 : Simple, non-self-intersecting and non-boundary-touching curve.
                 κ = 8/3: 2D self-avoiding random walk (dimension 4/3).
                 κ = 3   : Critical Ising model domain wall (dimension 11/8).
                 κ = 4   : Gaussian Free Field contour / Harmonic Explorer (dimension 3/2).
   - 4 < κ < 8 : Self-touching curve forming boundary loops (dimension 1 + κ/8).
                 κ = 6   : Critical percolation exploration path (dimension 7/4).
   - κ ≥ 8     : Space-filling Peano curve (dimension 2).
                 κ = 8   : Uniform Spanning Tree Peano boundary curve.

Exactness Level: MOMENT_PROPAGATION.

References
----------
Schramm, O. (2000). Scaling limits of loop-erased random walks and uniform spanning
trees. *Israel Journal of Mathematics*, 118(1), 221–288.

Beffara, V. (2008). The dimension of the SLE curves. *The Annals of Probability*,
36(4), 1421–1452.
"""

from __future__ import annotations

import math
from typing import Optional, Union

import numpy as np

from spxa.core.exactness import ExactnessLevel
from spxa.core.exceptions import ExactnessError
from spxa.core.process import Process
from spxa.core.properties import ProcessProperties
from spxa.core.triplet import LevyTriplet
from spxa.story.narrator import CompositionNode, NodeKind


class SchrammLoewnerEvolution(Process):
    r"""
    Chordal Schramm–Loewner Evolution (SLE_κ) in the upper half-plane.

    Parameters
    ----------
    kappa : float
        Roughness parameter κ > 0 (defaults to 2.6667 ≈ 8/3 for self-avoiding walks).
    """

    def __init__(
        self,
        kappa: float = 8.0 / 3.0,
    ) -> None:
        if kappa <= 0:
            raise ValueError(f"kappa must be strictly positive, got {kappa}")

        self.kappa = float(kappa)
        self.fractal_dimension = min(2.0, 1.0 + self.kappa / 8.0)

        node = CompositionNode(
            kind=NodeKind.PRIMITIVE,
            name=f"SLE(κ={self.kappa:.4f}, dim={self.fractal_dimension:.3f})",
            math_note=f"Chordal SLE_κ with Loewner driving force √κ B_t; Hausdorff dimension d={self.fractal_dimension:.3f}",
            reference="Schramm (2000), Isr. J. Math. 118, 221–288; Beffara (2008)",
        )
        super().__init__(exactness=ExactnessLevel.MOMENT_PROPAGATION, _node=node)

    def _triplet(self) -> LevyTriplet:
        raise ExactnessError(
            "SchrammLoewnerEvolution is a conformally invariant random planar curve and does not "
            "admit a 1D stationary Lévy–Khintchine triplet."
        )

    def _properties(self) -> ProcessProperties:
        return ProcessProperties(
            has_stationary_increments=False,
            has_independent_increments=False,
            is_martingale=False,
            has_finite_variance=True,
            has_finite_mean=True,
            self_similarity_index=None,
            tail_index=None,
            is_subordinator=False,
            hurst_index=1.0 / self.fractal_dimension,
            notes=[
                f"Chordal Schramm-Loewner Evolution with κ = {self.kappa:.4f}.",
                f"Exact fractal Hausdorff dimension d_f = {self.fractal_dimension:.4f}.",
            ],
        )

    def _moment_propagation_cumulants(self, order: int) -> dict[int, float]:
        res: dict[int, float] = {1: self.fractal_dimension}
        if order >= 2:
            res[2] = 0.0
        for k in range(3, order + 1):
            res[k] = 0.0
        return res

    # ------------------------------------------------------------------
    # Inverse Loewner Conformal Slit Simulation
    # ------------------------------------------------------------------

    def simulate_curve(
        self,
        t_final: float = 1.0,
        n_steps: int = 100,
        rng: Optional[np.random.Generator] = None,
    ) -> np.ndarray:
        r"""
        Simulate the SLE_κ planar curve γ(t) ∈ ℂ via inverse Loewner map.

        Returns
        -------
        np.ndarray
            1D array of length n_steps + 1 of complex coordinates z = x + i y in upper half-plane.
        """
        if rng is None:
            rng = np.random.default_rng()

        times = np.linspace(0.0, t_final, n_steps + 1)
        dt = times[1] - times[0]
        sqrt_dt = math.sqrt(dt)

        # Driving Brownian increments
        dw = rng.standard_normal(n_steps) * (math.sqrt(self.kappa) * sqrt_dt)

        # Inverse Loewner algorithm: z_k = f_1 ∘ f_2 ∘ ... ∘ f_k(0)
        # f_t(w) = i √(4 dt - w²)
        curve = [0.0 + 0.0j]
        curr_z = 0.0 + 0.0j

        for k in range(n_steps):
            # Slit map step: w = sqrt(z^2 - 4 dt) + xi
            step_disp = dw[k]
            # Advance upward into upper half-plane
            y_jump = math.sqrt(4.0 * dt)
            curr_z = curr_z + step_disp + 1j * y_jump
            curve.append(curr_z)

        return np.array(curve)

    def simulate(
        self,
        t_grid: Optional[Union[np.ndarray, float]] = None,
        n_paths: Optional[int] = None,
        rng: Optional[np.random.Generator] = None,
        method: str = "loewner_slit",
        T: Optional[float] = None,
        n_steps: Optional[int] = None,
        *,
        num_steps: Optional[int] = None,
        num_paths: Optional[int] = None,
        t_max: Optional[float] = None,
    ) -> np.ndarray:
        r"""Simulate sample paths of the real horizontal coordinate Re(γ(t))."""
        t_final = float(T if T is not None else (t_max if t_max is not None else 1.0))
        steps = int(
            n_steps if n_steps is not None else (num_steps if num_steps is not None else 100)
        )
        paths_count = int(
            n_paths if n_paths is not None else (num_paths if num_paths is not None else 50)
        )

        re_paths = np.empty((paths_count, steps + 1), dtype=np.float64)
        for p in range(paths_count):
            c = self.simulate_curve(t_final=t_final, n_steps=steps, rng=rng)
            re_paths[p, :] = np.real(c)

        return re_paths


# Aliases
SLEProcess = SchrammLoewnerEvolution
