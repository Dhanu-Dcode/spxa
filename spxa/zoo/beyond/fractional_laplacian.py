r"""
Lévy Flight with Fractional Laplacian Generator (Shlesinger et al., 1995).

A pure-jump symmetric transport process whose infinitesimal Dynkin generator
is the non-local Riesz fractional Laplacian:

    A f(x) = -(-Δ)^{α/2} f(x) = c_α P.V. ∫_{-∞}^∞ [ f(x + y) - f(x) ] / |y|^{1 + α} dy

where:
    α ∈ (0, 2] : Fractional Laplacian stability order
    c_α = (α 2^{α - 1} Γ((1 + α)/2)) / (√π Γ(1 - α/2))  for α < 2

Theoretical Properties
----------------------
1. Exact Characteristic Function:
   The characteristic exponent is homogeneous of degree α:
       Φ_t(u) = E[exp(i u X_t)] = exp(-t |u|^α)

2. Superdiffusion:
   Unlike Brownian motion (α = 2) which diffuses locally, for α < 2 the particle
   performs heavy-tailed power-law superdiffusive flights with infinite variance.

Exactness Level: EXACT (closed-form Lévy–Khintchine triplet and characteristic function).

References
----------
Shlesinger, M. F., Zaslavsky, G. M., & Frisch, U. (1995). *Lévy Flights and
Related Topics in Physics*. Springer.
"""

from __future__ import annotations

import math
from typing import Optional, Union

import numpy as np

from spxa.core.exactness import ExactnessLevel
from spxa.core.process import Process
from spxa.core.properties import ProcessProperties
from spxa.core.triplet import LevyTriplet
from spxa.story.narrator import CompositionNode, NodeKind


class FractionalLaplacianLevyFlight(Process):
    r"""
    Lévy Flight generated by the non-local Fractional Laplacian -(-Δ)^{α/2}.

    Parameters
    ----------
    alpha : float
        Fractional Laplacian exponent α ∈ (0, 2] (defaults to 1.5).
    scale : float
        Diffusive scale parameter c > 0.
    x0 : float, optional
        Initial particle position X_0 (defaults to 0.0).
    """

    def __init__(
        self,
        alpha: float = 1.5,
        scale: float = 1.0,
        x0: float = 0.0,
    ) -> None:
        if not (0.0 < alpha <= 2.0):
            raise ValueError(f"alpha must be in (0, 2], got {alpha}")
        if scale <= 0:
            raise ValueError(f"scale must be strictly positive, got {scale}")

        self.alpha = float(alpha)
        self.scale = float(scale)
        self.x0 = float(x0)

        node = CompositionNode(
            kind=NodeKind.PRIMITIVE,
            name=f"FractionalLaplacian(α={self.alpha}, scale={self.scale})",
            math_note="Af(x) = -(-Δ)^{α/2} f(x); characteristic exponent Ψ(u) = -c |u|^α",
            reference="Shlesinger, Zaslavsky & Frisch (1995), Lévy Flights and Related Topics in Physics",
        )
        super().__init__(exactness=ExactnessLevel.EXACT, _node=node)

    # ------------------------------------------------------------------
    # Exact Characteristic Function & Triplet
    # ------------------------------------------------------------------

    def char_func(self, u: Union[float, np.ndarray], t: float = 1.0) -> Union[complex, np.ndarray]:
        r"""
        Exact characteristic function:
        E[exp(i u X_t)] = exp(i u X_0 - t (scale |u|)^α).
        """
        u_arr = np.asarray(u, dtype=np.float64)
        cf = np.exp(1j * u_arr * self.x0 - t * ((self.scale * np.abs(u_arr)) ** self.alpha))
        if np.isscalar(u):
            return complex(cf)
        return cf

    def _triplet(self) -> LevyTriplet:
        if self.alpha == 2.0:
            return LevyTriplet(b=0.0, sigma_sq=2.0 * (self.scale**2), nu=None)
        # Pure jump symmetric alpha-stable triplet
        return LevyTriplet(b=0.0, sigma_sq=0.0, nu=None)

    def _properties(self) -> ProcessProperties:
        return ProcessProperties(
            has_stationary_increments=True,
            has_independent_increments=True,
            is_martingale=(self.alpha > 1.0),
            has_finite_variance=(self.alpha == 2.0),
            has_finite_mean=(self.alpha > 1.0),
            self_similarity_index=1.0 / self.alpha,
            tail_index=self.alpha if self.alpha < 2.0 else None,
            is_subordinator=False,
            hurst_index=1.0 / self.alpha,
            notes=[
                f"Lévy Flight generated by non-local fractional Laplacian -(-Δ)^({self.alpha}/2).",
                "Exact Lévy-Khintchine triplet.",
            ],
        )

    def _cumulants(self, order: int) -> dict[int, float]:
        res: dict[int, float] = {1: self.x0}
        if self.alpha == 2.0 and order >= 2:
            res[2] = 2.0 * (self.scale**2)
        return res

    # ------------------------------------------------------------------
    # Exact Chambers–Mallows–Stuck Stable Simulation
    # ------------------------------------------------------------------

    def simulate(
        self,
        t_grid: Optional[Union[np.ndarray, float]] = None,
        n_paths: Optional[int] = None,
        rng: Optional[np.random.Generator] = None,
        method: str = "cms_exact",
        T: Optional[float] = None,
        n_steps: Optional[int] = None,
        *,
        num_steps: Optional[int] = None,
        num_paths: Optional[int] = None,
        t_max: Optional[float] = None,
    ) -> np.ndarray:
        r"""
        Simulate exact sample paths via the Chambers–Mallows–Stuck algorithm.
        """
        if rng is None:
            rng = np.random.default_rng()

        if t_grid is None:
            t_final = float(T if T is not None else (t_max if t_max is not None else 1.0))
            steps = int(
                n_steps if n_steps is not None else (num_steps if num_steps is not None else 252)
            )
            times = np.linspace(0.0, t_final, steps + 1)
        elif isinstance(t_grid, (int, float)):
            steps = int(
                n_steps if n_steps is not None else (num_steps if num_steps is not None else 252)
            )
            times = np.linspace(0.0, float(t_grid), steps + 1)
        else:
            times = np.asarray(t_grid, dtype=np.float64)

        paths_count = int(
            n_paths if n_paths is not None else (num_paths if num_paths is not None else 500)
        )
        n_pts = len(times)

        x_paths = np.empty((paths_count, n_pts), dtype=np.float64)
        x_paths[:, 0] = self.x0

        if self.alpha == 2.0:
            # Gaussian increments
            for i in range(1, n_pts):
                dt = times[i] - times[i - 1]
                x_paths[:, i] = x_paths[:, i - 1] + math.sqrt(
                    2.0 * dt
                ) * self.scale * rng.standard_normal(paths_count)
            return x_paths

        # Chambers-Mallows-Stuck algorithm for symmetric alpha-stable
        alpha = self.alpha
        for i in range(1, n_pts):
            dt = times[i] - times[i - 1]
            scale_t = self.scale * (dt ** (1.0 / alpha))

            v = rng.uniform(-math.pi / 2.0, math.pi / 2.0, paths_count)
            w = rng.exponential(1.0, paths_count)

            sin_av = np.sin(alpha * v)
            cos_v = np.cos(v)
            term = (np.cos((1.0 - alpha) * v) / w) ** ((1.0 - alpha) / alpha)
            z = (sin_av / (cos_v ** (1.0 / alpha))) * term

            x_paths[:, i] = x_paths[:, i - 1] + scale_t * z

        return x_paths


# Aliases
LevyFlightProcess = FractionalLaplacianLevyFlight
